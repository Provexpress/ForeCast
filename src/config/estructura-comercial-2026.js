  function normalizeEmail(value){
    return String(value || '').toLowerCase().trim();
  }

  function fileBaseName(fileName){
    return String(fileName || '').replace(/\.(xlsx|xls)$/i, '').trim();
  }

  function normalizeName(value){
    return String(value || '')
      .replace(/\.(xlsx|xls)$/i, '')
      .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .replace(/[^a-z0-9\s]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function getDirectorEntries(){
    return Object.entries(ESTRUCTURA_COMERCIAL_2026.directores)
      .sort((a, b) => Number(a[1].grupo) - Number(b[1].grupo));
  }

  function getExecutiveEntries(){
    return Object.entries(ESTRUCTURA_COMERCIAL_2026.ejecutivos);
  }

  function getDirectorByGroup(grupo){
    const target = Number(grupo);
    const entry = getDirectorEntries().find(([, data]) => Number(data.grupo) === target);
    return entry ? { email: entry[0], ...entry[1] } : null;
  }

  function getDirectorByEmail(email){
    const normalized = normalizeEmail(email);
    const data = ESTRUCTURA_COMERCIAL_2026.directores[normalized];
    return data ? { email: normalized, ...data } : null;
  }

  function getExecutiveByEmail(email){
    const normalized = normalizeEmail(email);
    const data = ESTRUCTURA_COMERCIAL_2026.ejecutivos[normalized];
    return data ? { email: normalized, ...data } : null;
  }

  function getSupportByEmail(email){
    const normalized = normalizeEmail(email);
    const unit = ESTRUCTURA_COMERCIAL_2026.salesSupport[normalized];
    if(unit) return { email: normalized, role: 'sales_support', scope: 'unit', ...unit };
    const commercial = ESTRUCTURA_COMERCIAL_2026.salesSupportComerciales[normalized];
    if(commercial) return { email: normalized, role: 'sales_support_comercial', scope: 'commercial', ...commercial };
    return null;
  }

  function getRoleByEmail(email){
    const normalized = normalizeEmail(email);
    const isGerencia = ESTRUCTURA_COMERCIAL_2026.gerencia.includes(normalized);
    const isDirector = !!ESTRUCTURA_COMERCIAL_2026.directores[normalized];
    if(isGerencia && isDirector) return 'gerencia_director';
    if(isGerencia) return 'gerencia';
    if(ESTRUCTURA_COMERCIAL_2026.directores[normalized]) return 'director';
    if(ESTRUCTURA_COMERCIAL_2026.ejecutivos[normalized]) return 'ejecutivo';
    if(ESTRUCTURA_COMERCIAL_2026.salesSupport[normalized]) return 'sales_support';
    if(ESTRUCTURA_COMERCIAL_2026.salesSupportComerciales[normalized]) return 'sales_support_comercial';
    return null;
  }

  function getGroupByEmail(email){
    const normalized = normalizeEmail(email);
    const director = ESTRUCTURA_COMERCIAL_2026.directores[normalized];
    if(director) return director.grupo;
    const executive = ESTRUCTURA_COMERCIAL_2026.ejecutivos[normalized];
    if(executive) return executive.grupo;
    const support = ESTRUCTURA_COMERCIAL_2026.salesSupport[normalized];
    if(support) return support.grupo;
    const commercialSupport = ESTRUCTURA_COMERCIAL_2026.salesSupportComerciales[normalized];
    if(commercialSupport && commercialSupport.soportaA && commercialSupport.soportaA.length) {
      const supported = getExecutiveByEmail(commercialSupport.soportaA[0]);
      return supported ? supported.grupo : null;
    }
    return null;
  }

  function getFolderByGroup(grupo){
    const director = getDirectorByGroup(grupo);
    return director ? director.carpeta : '';
  }

  function getDirectorNameByGroup(grupo){
    const director = getDirectorByGroup(grupo);
    return director ? director.nombre : '';
  }

  function getDirectorFolderByEmail(email){
    return getFolderByGroup(getGroupByEmail(email));
  }

  function getDirectorFolderByName(name){
    const target = normalizeName(name);
    const director = getDirectorEntries().find(([, data]) =>
      normalizeName(data.nombre) === target ||
      normalizeName(data.carpeta) === target ||
      normalizeName(data.carpeta.replace(/^Grupo\s+/i, '')) === target
    );
    return director ? director[1].carpeta : '';
  }

  function getEjecutivosByDirector(email){
    const group = getGroupByEmail(email);
    if(!group) return [];
    return getExecutiveEntries()
      .filter(([, data]) => Number(data.grupo) === Number(group))
      .map(([executiveEmail]) => executiveEmail);
  }

  function getEjecutivosBySupport(email){
    const normalized = normalizeEmail(email);
    const unit = ESTRUCTURA_COMERCIAL_2026.salesSupport[normalized];
    if(unit && unit.apoyaUnidad) return getExecutiveEntries().map(([executiveEmail]) => executiveEmail);
    const commercial = ESTRUCTURA_COMERCIAL_2026.salesSupportComerciales[normalized];
    return commercial ? (commercial.soportaA || []).map(normalizeEmail).filter(Boolean) : [];
  }

